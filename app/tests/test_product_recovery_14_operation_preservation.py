def _verdict(
    *,
    accepted=False,
    status="repair_required",
    reasons=None,
    rule_ids=None,
    findings=None,
    details=None,
):
    reasons = list(reasons or [])
    rule_ids = list(rule_ids or [])
    details = dict(details or {})
    if rule_ids:
        details.setdefault("validator_rule_ids", rule_ids)
    return SimpleNamespace(
        accepted=accepted,
        status=status,
        reasons=reasons,
        validator_rule_ids=rule_ids,
        findings=[] if findings is None else findings,
        details=details,
        verdict={"status": status},
        warning=False,
    )


