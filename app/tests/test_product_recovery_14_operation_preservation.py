def _step(number, description, *, commands=None, verification=None, ops=None):
    return {
        "step_number": number,
        "description": description,
        "commands": list(commands or []),
        "verification": verification,
        "rollback": None,
        "expected_files": [],
        "ops": deepcopy(ops or []),
    }


