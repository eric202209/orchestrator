def _run_generic_repair_flow(
    tmp_path,
    monkeypatch,
    *,
    repaired_plan,
    original_verdict=None,
    final_verdicts=None,
    normalize_mutator=None,
    post_gate_mutator=None,
):
    original_verdict = original_verdict or _pr12_original_rejection()
    final_verdicts = list(
        final_verdicts or [_verdict(accepted=True, status="accepted")]
    )
    project_dir = Path(tmp_path)
    source_file = project_dir / "dataflow" / "aggregate.py"
    source_file.parent.mkdir(parents=True, exist_ok=True)
    source_file.write_text(
        "from typing import Iterable\n\n"
        "def normalize_records(records):\n    return records\n\n"
        + PR08_ORIGINAL_REPLACE["old"]
        + "\n\n"
        "def totals_by_region(records):\n    return {}\n",
        encoding="utf-8",
    )

    orchestration_state = SimpleNamespace(
        project_dir=project_dir,
        project_id=12,
        project_context="",
        plan=[],
        current_step_index=0,
        reasoning_artifact=None,
        status="planning",
        abort_reason="",
    )

    runtime_calls = []

    class Runtime:
        def get_backend_metadata(self):
            return {}

        async def execute_task(self, *args, **kwargs):
            runtime_calls.append(kwargs.get("diagnostic_label"))
            if kwargs.get("diagnostic_label") == "PLANNING_DISCOVERY":
                return {"status": "completed", "output": '{"action":"stop"}'}
            return {"status": "completed", "output": json.dumps(_original_plan())}

    task = SimpleNamespace(
        id=140,
        title="Repair command contract",
        description="Repair the command contract while preserving the existing edit",
        execution_profile="full_lifecycle",
        steps=None,
        current_step=0,
        status="pending",
    )
    session = SimpleNamespace(id=6031, status="running", is_active=True)
    session_task_link = SimpleNamespace(status="pending")
    emitted = []
    ctx = OrchestrationRunContext(
        db=_DatabaseStub(),
        session=session,
        project=SimpleNamespace(id=12, path=str(project_dir), name="PR14 scratch"),
        task=task,
        session_task_link=session_task_link,
        session_id=640,
        task_id=140,
        prompt=task.description,
        timeout_seconds=300,
        execution_profile="full_lifecycle",
        validation_profile="standard",
        runs_in_canonical_baseline=False,
        orchestration_state=orchestration_state,
        runtime_service=Runtime(),
        task_service=SimpleNamespace(handle_task_failure=lambda *args, **kwargs: None),
        logger=logging.getLogger("test.product_recovery_14"),
        emit_live=lambda *args, **kwargs: emitted.append((args, kwargs)),
        error_handler=SimpleNamespace(last_planning_parse_metadata={}),
    )
    ctx.error_handler.attempt_json_parsing = lambda output, **kwargs: (
        True,
        json.loads(output),
        "json",
    )
    restore_calls = []
    ctx.restore_workspace_snapshot_if_needed = lambda reason: restore_calls.append(
        reason
    )

    _patch_planning_flow_external_writes(monkeypatch)
    phase_events = []
    monkeypatch.setattr(
        planning_flow,
        "emit_phase_event",
        lambda state, emitter, **kwargs: phase_events.append(kwargs),
    )
    monkeypatch.setattr(
        PlannerService,
        "should_start_with_minimal_prompt",
        staticmethod(lambda *args, **kwargs: False),
    )
    monkeypatch.setattr(
        PlannerService,
        "find_immediate_repair_step_issues",
        staticmethod(lambda *args, **kwargs: {}),
    )
    monkeypatch.setattr(
        planning_flow,
        "_ground_post_plan_sources_or_abort_missing",
        lambda **kwargs: None,
    )
    monkeypatch.setattr(
        planning_flow,
        "arbitrate_planning_repair_candidate",
        lambda **kwargs: {"action": "none"},
    )
    guidance_calls = []

    def guidance(ctx, **kwargs):
        guidance_calls.append(ctx.orchestration_state.plan)
        if post_gate_mutator is not None and len(guidance_calls) == 2:
            post_gate_mutator(ctx.orchestration_state.plan)
        return None

    monkeypatch.setattr(planning_flow, "_run_guidance_plan_enforcement", guidance)
    monkeypatch.setattr(
        planning_flow,
        "_build_reasoning_artifact",
        lambda *args, **kwargs: {
            "intent": "Preserve source edit",
            "workspace_facts": [],
            "planned_actions": [],
            "verification_plan": ["Run the focused test"],
        },
    )
    monkeypatch.setattr(
        ValidatorService,
        "validate_reasoning_artifact",
        staticmethod(
            lambda *args, **kwargs: _verdict(accepted=True, status="accepted")
        ),
    )
    validator_calls = []
    available_verdicts = [original_verdict, *final_verdicts]

    def validate_plan(*args, **kwargs):
        validator_calls.append(kwargs)
        return available_verdicts[
            min(len(validator_calls) - 1, len(available_verdicts) - 1)
        ]

    monkeypatch.setattr(ValidatorService, "validate_plan", staticmethod(validate_plan))
    repair_calls = []

    def repair_output(cls, *args, **kwargs):
        repair_calls.append(kwargs)
        return {"output": json.dumps(repaired_plan)}

    monkeypatch.setattr(PlannerService, "repair_output", classmethod(repair_output))

    def normalize(*args, **kwargs):
        plan = deepcopy(args[3])
        if normalize_mutator is not None and len(repair_calls) > 0:
            normalize_mutator(plan)
        return plan

    result = execute_planning_phase(
        ctx=ctx,
        workspace_review={"has_existing_files": True},
        extract_structured_text=extract_structured_text,
        extract_plan_steps=lambda value: value if isinstance(value, list) else None,
        looks_like_truncated_multistep_plan=lambda text, plan: False,
        normalize_plan_with_live_logging=normalize,
        workspace_violation_error_cls=RuntimeError,
    )
    return SimpleNamespace(
        result=result,
        ctx=ctx,
        task=task,
        repair_calls=repair_calls,
        validator_calls=validator_calls,
        runtime_calls=runtime_calls,
        emitted=emitted,
        phase_events=phase_events,
        restore_calls=restore_calls,
    )


def test_t2_generic_repair_gate_rejects_before_final_validator_persistence_or_execution(
    tmp_path, monkeypatch
):
    run = _run_generic_repair_flow(
        tmp_path,
        monkeypatch,
        repaired_plan=_pr12_retained_repair_plan(),
    )

    assert run.result == {
        "status": "failed",
        "reason": "planning_validation_failed_after_repair",
    }
    assert len(run.repair_calls) == 1
    assert len(run.validator_calls) == 1  # original rejection only
    assert run.task.steps is None
    assert not any(label == "EXECUTION" for label in run.runtime_calls)
    diagnostics = [event.get("details") for event in run.phase_events]
    preservation = next(
        item
        for item in diagnostics
        if isinstance(item, dict)
        and item.get("reason") == "command_only_repair_operation_preservation_failed"
    )
    assert preservation["gate_stage"] == "post_normalization"
    assert preservation["operation_preservation"]["change_counts"]["modified"] == 1
    assert run.restore_calls


